def _badge(severity: str) -> str:
    level = (severity or "info").lower()
    return f'<span class="badge b-{level}">{html.escape(level)}</span>'


def _table(headers, rows, empty="No results") -> str:
    if not rows:
        return f'<div class="empty">{html.escape(empty)}</div>'
    head = "".join(f"<th>{html.escape(str(h))}</th>" for h in headers)
    body = "".join(
        "<tr>" + "".join(f"<td>{cell}</td>" for cell in row) + "</tr>" for row in rows
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def _cards(items) -> str:
    cards = "".join(
        f'<div class="card"><div class="k">{html.escape(str(k))}</div>'
        f'<div class="v">{html.escape(str(v))}</div></div>'
        for k, v in items if v not in (None, "", [], {})
    )
    return f'<div class="grid">{cards}</div>' if cards else ""


# --- section builders -------------------------------------------------------

def _sec_scan(data: dict) -> str:
    parts = [f"<h2>Port Scan · {html.escape(str(data.get('target','')))}</h2>"]
    parts.append(_cards([
        ("Target", data.get("target")),
        ("Resolved IP", data.get("ip")),
        ("Ports scanned", data.get("ports_scanned")),
        ("Open ports", len(data.get("open") or [])),
        ("Duration", f"{data.get('duration')} s"),
    ]))
    rows = []
    for entry in data.get("open") or []:
        rows.append([
            f"<code>{entry.get('port')}</code>",
            html.escape(str(entry.get("service"))),
            html.escape(str(entry.get("banner") or "—")),
            html.escape(str(entry.get("latency_ms"))),
        ])
    parts.append(_table(["Port", "Service", "Banner", "Latency (ms)"], rows, "No open ports found"))
    risks = data.get("risk") or []
    if risks:
        parts.append("<h2>Risk Flags</h2>")
        parts.append(_table(["Severity", "Port", "Service", "Advice"], [
            [_badge(item.get("severity")), f"<code>{item.get('port')}</code>",
             html.escape(str(item.get("service"))), html.escape(str(item.get("advice")))]
            for item in risks
        ]))
    return "".join(parts)


def _sec_dns(data: dict) -> str:
    parts = [f"<h2>DNS · {html.escape(str(data.get('domain') or data.get('target','')))}</h2>"]
    records = data.get("records") or {}
    if records:
        rows = []
        for rtype, values in records.items():
            for item in values:
                value = item.get("value") if isinstance(item, dict) else item
                ttl = item.get("ttl") if isinstance(item, dict) else ""
                rows.append([f"<code>{html.escape(str(rtype))}</code>",
                             html.escape(_render(value)), html.escape(str(ttl or "—"))])
        parts.append(_table(["Type", "Value", "TTL"], rows))
    else:
        parts.append('<div class="empty">No DNS records returned</div>')
    return "".join(parts)


def _sec_whois(data: dict) -> str:
    parts = [f"<h2>WHOIS · {html.escape(str(data.get('query','')))}</h2>"]
    fields = data.get("fields") or {}
    if fields:
        parts.append(_cards([(k.replace("_", " ").title(), _render(v)) for k, v in fields.items()]))
    else:
        parts.append('<div class="empty">No parsed WHOIS fields</div>')
    return "".join(parts)


def _sec_ip(data: dict) -> str:
    parts = [f"<h2>IP Intelligence · {html.escape(str(data.get('query','')))}</h2>"]
    parts.append(_cards([
        ("IP", data.get("ip")), ("Reverse DNS", data.get("reverse")),
        ("Country", data.get("country")), ("Region", data.get("region")),
        ("City", data.get("city")), ("ISP", data.get("isp")),
        ("Organisation", data.get("org")), ("ASN", data.get("asn")),
        ("Timezone", data.get("timezone")),
        ("Coordinates", f"{data.get('latitude')}, {data.get('longitude')}"
         if data.get("latitude") is not None else None),
        ("Hosting", data.get("hosting")), ("Proxy/VPN", data.get("proxy")),
    ]))
    return "".join(parts)


def _sec_web(data: dict) -> str:
    parts = [f"<h2>Web Header Audit · {html.escape(str(data.get('url','')))}</h2>"]
    parts.append(_cards([
        ("Status", f"{data.get('status')} {data.get('reason') or ''}"),
        ("Server", data.get("server")),
        ("Security grade", data.get("grade")),
        ("Score", f"{data.get('score')}/{data.get('max_score')}"),
        ("Redirects", len(data.get("redirects") or [])),
        ("Technologies", ", ".join(data.get("technologies") or []) or None),
    ]))
    rows = []
    for item in data.get("security") or []:
        state = '<span class="ok">present</span>' if item.get("present") else '<span class="bad">missing</span>'
        rows.append([f"<code>{html.escape(item.get('header'))}</code>", state,
                     html.escape(str(item.get("value") or "—"))])
    parts.append(_table(["Header", "State", "Value"], rows))
    if data.get("missing"):
        parts.append("<h2>Recommendations</h2>")
        parts.append(_table(["Header", "Advice"], [
            [f"<code>{html.escape(str(item.get('header')))}</code>", html.escape(str(item.get("advice")))]
            for item in data["missing"]
        ]))
    if data.get("cookies"):
        parts.append("<h2>Cookies</h2>")
        parts.append(_table(["Cookie", "Issues"], [
            [f"<code>{html.escape(str(item.get('name')))}</code>",
             html.escape(", ".join(item.get("issues") or []) or "flags look good")]
            for item in data["cookies"]
        ]))
    return "".join(parts)


def _sec_ssl(data: dict) -> str:
    parts = [f"<h2>TLS Certificate · {html.escape(str(data.get('host','')))}:{data.get('port')}</h2>"]
    status = "ok" if data.get("ok") else "error"
    parts.append(_cards([
        ("Status", status), ("Subject CN", (data.get("subject") or {}).get("commonName")),
        ("Issuer", (data.get("issuer") or {}).get("organizationName") or (data.get("issuer") or {}).get("commonName")),
        ("Valid from", data.get("not_before")), ("Valid until", data.get("not_after")),
        ("Days left", data.get("days_left")), ("TLS version", data.get("version")),
        ("Cipher", data.get("cipher")), ("Bits", data.get("bits")),
        ("Chain trusted", data.get("chain_trusted")),
        ("Self signed", data.get("self_signed")),
        ("SHA-256", data.get("sha256")),
    ]))
    if data.get("san"):
        parts.append("<h2>Subject Alternative Names</h2>")
        parts.append('<div class="card"><code>' +
                     "<br>".join(html.escape(n) for n in data["san"]) + "</code></div>")
    if data.get("protocol_warnings"):
        parts.append("<h2>Warnings</h2>")
        parts.append(_table(["Warning"], [[html.escape(w)] for w in data["protocol_warnings"]]))
    return "".join(parts)


def _sec_sub(data: dict) -> str:
    parts = [f"<h2>Subdomains · {html.escape(str(data.get('domain','')))}</h2>"]
    parts.append(_cards([
        ("Domain", data.get("domain")), ("Found", len(data.get("found") or [])),
        ("Checked", data.get("total_checked")), ("Sources", ", ".join(data.get("sources") or []) or None),
        ("Wildcard DNS", ", ".join(data.get("wildcard") or []) or "none"),
    ]))
    rows = [[html.escape(str(item.get("subdomain"))),
             "<br>".join(html.escape(i) for i in (item.get("ips") or [])),
             html.escape(", ".join(item.get("cnames") or []) or "—"),
             html.escape(str(item.get("source") or "—"))]
            for item in data.get("found") or []]
    parts.append(_table(["Subdomain", "IPs", "CNAME", "Source"], rows, "No subdomains resolved"))
    return "".join(parts)


def _sec_dir(data: dict) -> str:
    parts = [f"<h2>Path Discovery · {html.escape(str(data.get('url','')))}</h2>"]
    baseline = data.get("baseline") or {}
    parts.append(_cards([
        ("Target", data.get("url")), ("Paths tested", data.get("tested")),
        ("Found", len(data.get("found") or [])), ("Duration", f"{data.get('duration')} s"),
        ("Baseline status", baseline.get("status")),
    ]))
    rows = []
    for item in data.get("found") or []:
        status = item.get("status")
        cls = "ok" if status == 200 else ("warn" if status and status < 400 else "bad")
        rows.append([
            f"<code>{html.escape(str(item.get('path')))}</code>",
            f'<span class="{cls}">{status}</span>',
            html.escape(str(item.get("length"))),
            html.escape(str(item.get("redirect") or "—")),
        ])
    parts.append(_table(["Path", "Status", "Length", "Redirect"], rows, "No paths discovered"))
    return "".join(parts)


def _sec_sysinfo(data: dict) -> str:
    parts = ["<h2>System Information</h2>"]
    parts.append(_cards([(k.replace("_", " ").title(), _render(v))
                         for k, v in data.items() if not isinstance(v, (dict, list))]))
    for key in ("cpu", "memory", "storage_home", "network", "installed"):
        value = data.get(key)
        if isinstance(value, dict):
            parts.append(f"<h2>{html.escape(key.replace('_',' ').title())}</h2>")
            parts.append(_cards(list(value.items())))
    return "".join(parts)


def _sec_generic(data: dict) -> str:
    parts = ["<h2>Results</h2>"]
    if isinstance(data, dict):
        parts.append(_cards([(k, _render(v)) for k, v in data.items()
                             if not isinstance(v, (dict, list))]))
        for key, value in data.items():
            if isinstance(value, list) and value and isinstance(value[0], dict):
                headers = list(value[0].keys())
                rows = [[html.escape(_render(row.get(h))) for h in headers] for row in value]
                parts.append(f"<h2>{html.escape(key.replace('_',' ').title())}</h2>")
                parts.append(_table(headers, rows))
    return "".join(parts)


SECTION_BUILDERS = {
    "scan": _sec_scan,
    "dns": _sec_dns,
    "whois": _sec_whois,
    "ip": _sec_ip,
    "web": _sec_web,
    "ssl": _sec_ssl,
    "subdomains": _sec_sub,
    "dirscan": _sec_dir,
    "sysinfo": _sec_sysinfo,
}


def _render(value) -> str:
    if value is None:
        return "—"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, (list, tuple)):
        return ", ".join(_render(v) for v in value) if value else "—"
    if isinstance(value, dict):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


# --- public API -------------------------------------------------------------

def build_html(module: str, data: dict, duration: str = "—") -> str:
    builder = SECTION_BUILDERS.get(module, _sec_generic)
    try:
        body = builder(data)
    except Exception:  # noqa: BLE001 - a malformed section must not kill the report
        body = _sec_generic(data)
    title = f"{module.upper()} report"
    return HTML_TEMPLATE.format(
        title=html.escape(title),
        body=body,
        app=APP_NAME,
        version=VERSION,
        generated=now_iso(),
        duration=html.escape(duration),
    )


def build_text(module: str, data: dict, duration: str = "—") -> str:
    lines = [
        "=" * 68,
        f" {APP_NAME} v{VERSION} — {module.upper()} report",
        f" generated: {now_iso()}",
        f" duration : {duration}",
        "=" * 68,
        "",
        "⚠  Legal use only: your own systems or explicitly authorised targets.",
        "",
    ]
    lines.extend(_flatten_text(data, indent=0))
    return "\n".join(lines)


def _flatten_text(value, indent: int = 0) -> list:
    pad = "  " * indent
    out = []
    if isinstance(value, dict):
        for key, item in value.items():
            label = str(key).replace("_", " ")
            if isinstance(item, (dict, list)) and item:
                out.append(f"{pad}▸ {label}:")
                out.extend(_flatten_text(item, indent + 1))
            else:
                out.append(f"{pad}{label}: {_render(item)}")
    elif isinstance(value, list):
        if not value:
            out.append(f"{pad}—")
        for index, item in enumerate(value, 1):
            if isinstance(item, (dict, list)):
                out.append(f"{pad}[{index}]")
                out.extend(_flatten_text(item, indent + 1))
            else:
                out.append(f"{pad}- {_render(item)}")
    else:
        out.append(f"{pad}{_render(value)}")
    return out


def save_report(module: str, data: dict, fmt: str = "json", path: str = None,
                duration: str = "—") -> dict:
    """Write a report to disk and return {ok, path, fmt, bytes}."""
    cfg = load_config()
    directory = ensure_report_dir(cfg)
    fmt = (fmt or "json").lower()
    if fmt not in ("json", "html", "txt", "text", "all"):
        return {"ok": False, "error": f"unsupported format: {fmt}", "path": None}

    if path:
        target_path = os.path.expanduser(path)
        directory = os.path.dirname(target_path) or directory
        base, ext = os.path.splitext(target_path)
        stem = base if ext else target_path
    else:
        stem = os.path.join(directory, f"ruk_{module}_{now_stamp()}")

    written = []
    formats = ["json", "html", "txt"] if fmt == "all" else [("txt" if fmt == "text" else fmt)]
    payload = {
        "tool": APP_NAME,
        "version": VERSION,
        "module": module,
        "generated": now_iso(),
        "duration": duration,
        "data": data,
    }
    for current in formats:
        try:
            os.makedirs(directory, exist_ok=True)
            if current == "json":
                out_path = stem + ".json"
                with open(out_path, "w", encoding="utf-8") as fh:
                    json.dump(payload, fh, indent=2, ensure_ascii=False, default=str)
            elif current == "html":
                out_path = stem + ".html"
                with open(out_path, "w", encoding="utf-8") as fh:
                    fh.write(build_html(module, data, duration))
            else:
                out_path = stem + ".txt"
                with open(out_path, "w", encoding="utf-8") as fh:
                    fh.write(build_text(module, data, duration))
            written.append({"path": out_path, "bytes": os.path.getsize(out_path)})
        except OSError as exc:
            return {"ok": False, "error": str(exc), "path": None, "written": written}
    return {"ok": True, "path": written[0]["path"] if written else None,
            "written": written, "fmt": fmt}
